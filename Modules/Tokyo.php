<h1>Tokyo</h1>
    <p>Tokyo, the capital of Japan, is a sprawling, dynamic metropolis known
         for its striking blend of ultramodernity and deep-rooted tradition. 
         It is one of the world's largest and most populous cities, offering 
         everything from neon-lit skyscrapers and cutting-edge technology in
          areas like Shinjuku and Shibuya, to serene ancient temples and tranquil gardens,
           such as the historic Senso-ji or the Meiji Jingu Shrine. As a global center for fashion,
            cuisine, and culture, the city presents an unlimited array of experiences,
             all connected by a famously punctual and efficient public transport system.</p>